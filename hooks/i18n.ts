const UNIT: Record<string, string> = { s: 'ثانية', m: 'دقيقة', h: 'ساعة', d: 'يوم' }
const WINDOW: Record<string, string> = { weekly: 'الأسبوعي', daily: 'اليومي', '5-hour': 'الـ 5 ساعات', spend: 'الصرف' }

const PATTERNS: [RegExp, (m: RegExpMatchArray) => string][] = [
  [/^(\d+) connected$/i, m => `${m[1]} متوصل`],
  [/^● (\d+)\/(\d+) ready$/i, m => `● ${m[1]}/${m[2]} جاهز`],
  [/^(\d+(?:\.\d+)?)% used(?: · resets in (.+))?$/i, m => `مستخدم ${m[1]}%${m[2] ? ` · يتجدد بعد ${m[2]}` : ''}`],
  [/^(.+) limit$/i, m => `الحد ${WINDOW[m[1]!.toLowerCase()] ?? m[1]}`],
  [/^Show more · (\d+) left$/i, m => `عرض المزيد · باقي ${m[1]}`],
  [/^(\d+) models?$/i, m => `${m[1]} موديل`],
  [/^(\d+) reqs$/i, m => `${m[1]} طلب`],
  [/^Requests · (\d+)$/i, m => `الطلبات · ${m[1]}`],
  [/^Last (\d+) requests$/i, m => `آخر ${m[1]} طلب`],
  [/^(\d+) days?$/i, m => `${m[1]} يوم`],
  [/^(\d+) other providers?$/i, m => `${m[1]} provider تاني`],
  [/^Use for (.+)$/i, m => `استخدمه لـ ${m[1]}`],
  [/^(\d+)([smhd]) ago$/, m => `من ${m[1]} ${UNIT[m[2]!]}`],
  [/^From (.+) · checked (.+)$/i, m => `من ${m[1]} · اتفحص ${tr(m[2]!)}`],
  [/^Model list updated (.+?)( · out of date)?$/, m => `قايمة الموديلات اتحدثت ${tr(m[1]!)}${m[2] ? ' · قديمة' : ''}`],
  [/^(.+) \(your rule\)$/i, m => `${m[1]} (قاعدتك)`],
  [/^Why: (.+)$/i, m => `السبب: ${m[1]}`],
  [/^ \/ (.+)$/, m => ` / ${tr(m[1]!)}`],
  [/^✓ In use · set its effort on the (.+) page$/i, m => `✓ مستخدم · اختار الـ effort من صفحة ${m[1]}`],
  [/^(.+) is the CLI’s default\.$/i, m => `${tr(m[1]!)} هو الافتراضي في الـ CLI.`],
  [/^(.+): open the hub on desktop or terminal to type here\.$/i, m => `${tr(m[1]!)}: افتح الهب على الديسكتوب أو التيرمينال علشان تكتب هنا.`],
  [/^(\d+) chars$/i, m => `${m[1]} حرف`],
  [/^Running (.+) · (.+)$/, m => `شغال من ${m[1]} · ${m[2]}`],
  [/^(.+) received · last output (.+)$/, m => `وصل ${m[1]} · آخر output ${tr(m[2]!)}`],
  [/^(.+) received · no output yet$/, m => `وصل ${m[1]} · لسه مفيش output`],
  [/^This session · (\d+) subagents?$/, m => `الـ session دي · ${m[1]} subagent`],
]

/** The Arabic for one label, or the label itself where there is none. */
export function tr(s: string): string {
  const hit = AR[s.toLowerCase()] ?? AR[s.trim().toLowerCase()]
  if (hit) return hit
  for (const [re, fn] of PATTERNS) {
    const m = s.match(re)
    if (m) return fn(m)
  }
  return s
}

export const hasArabic = (s: string): boolean => /[؀-ۿ]/.test(s)
